export type Result={results:Record<string,any>[],meta:{changes:number}};
export type Query=(sql:string,args:any[])=>Promise<{rows:Record<string,any>[],count:number}>;
export type Prepared={sql:string,args:any[],bind:(...args:any[])=>Prepared,all:()=>Promise<Result>,run:()=>Promise<Result>};
export type Database={prepare:(sql:string)=>Prepared,batch:(statements:Prepared[])=>Promise<Result[]>};

/** Queries are authored by the service. Values always travel as bind parameters. */
export function postgresQuery(sql:string){
 let n=0,quoted=false,result='';
 const ignore=/^INSERT OR IGNORE\b/i.test(sql);
 sql=sql.replace(/^INSERT OR IGNORE\b/i,'INSERT');
 for(let i=0;i<sql.length;i++){
  const c=sql[i];
  if(c==="'"){if(quoted&&sql[i+1]==="'"){result+="''";i++;continue;}quoted=!quoted;}
  result+=c==='?'&&!quoted?`$${++n}`:c;
 }
 if(ignore)result+=' ON CONFLICT DO NOTHING';
 // Only fixed, allowlisted table identifiers can be generated by service.ts.
 const tables='audit|campaigns|catalogs|corrections|groups|histories|imports|issues|periods|preaching_types|profiles|publishers|reports|settings|users|assets';
 return result.replace(new RegExp(`\\b(FROM|INTO|UPDATE|JOIN)\\s+(${tables})\\b`,'gi'),(_all,op,table)=>`${op} s21.${table}`);
}

export function createDatabase(query:Query):Database{
 async function execute(s:Prepared):Promise<Result>{
  const result=await query(postgresQuery(s.sql),s.args);
  if(/\bWHERE\b[\s\S]*\bversion\s*=\s*\?/.test(s.sql)&&/^UPDATE\b/.test(s.sql)&&result.count===0){
   throw Object.assign(new Error('Otro usuario modificó este registro. Actualiza antes de guardar.'),{status:409});
  }
  return {results:result.rows,meta:{changes:result.count}};
 }
 function prepare(sql:string,args:any[]=[]):Prepared{
  const s:Prepared={sql,args,bind:(...values:any[])=>prepare(sql,values.map(v=>v===undefined?null:v)),all:()=>execute(s),run:()=>execute(s)};return s;
 }
 return {prepare,batch:async statements=>{
  const results:Result[]=[];
  for(const original of statements){
   const conditional=original.sql.includes('WHERE changes()>0');
   if(conditional&&!results.at(-1)?.meta.changes){results.push({results:[],meta:{changes:0}});continue;}
   const s=conditional?prepare(original.sql.replace('WHERE changes()>0',''),original.args):original;
   results.push(await execute(s));
  }
  return results;
 }};
}
